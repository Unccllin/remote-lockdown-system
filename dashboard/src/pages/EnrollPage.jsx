import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { ArrowLeft, Download, Copy, Check, Key, AlertTriangle, Package, Cloud } from 'lucide-react';
import toast from 'react-hot-toast';
import api from '../api/client';
import { useServerlessMode } from '../hooks/useServerlessMode';

export default function EnrollPage() {
  const navigate = useNavigate();
  const { serverless } = useServerlessMode();
  const [form, setForm] = useState({ hostname: '', owner_name: '' });
  const [loading, setLoading] = useState(false);
  const [enrolled, setEnrolled] = useState(null); // { device, apiKey }
  const [copied, setCopied] = useState(false);
  const [downloadingInstaller, setDownloadingInstaller] = useState(false);

  async function handleSubmit(e) {
    e.preventDefault();
    setLoading(true);
    try {
      const { data } = await api.post('/devices', form);
      setEnrolled({ device: data, apiKey: data.api_key });
      toast.success(`Device "${data.hostname}" enrolled successfully`);
    } catch (err) {
      toast.error(err.response?.data?.error || 'Enrollment failed. Check your input and try again. If the issue persists, verify the hostname is unique and the server is running.');
    } finally {
      setLoading(false);
    }
  }

  function copyApiKey() {
    navigator.clipboard.writeText(enrolled.apiKey);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
    toast.success('API key copied to clipboard');
  }

  function downloadAgentConfig() {
    const serverUrl = window.location.origin;
    const config = {
      server_url: serverUrl,
      device_hostname: enrolled.device.hostname,
      api_key: enrolled.apiKey,
      // Polling settings
      poll_interval: 30,
      // HMAC settings (Phase 0 security)
      sign_requests: true,
      // Server supports command_id dedup (Phase 0)
      server_supports_ack_dedup: true,
      // Boot lockdown enabled by default
      boot_lock_enabled: true,
      // Created timestamp
      enrolled_at: new Date().toISOString(),
    };

    const blob = new Blob([JSON.stringify(config, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `agent-config-${enrolled.device.hostname.toLowerCase().replace(/[^a-z0-9]/g, '-')}.json`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success('Agent config downloaded');
  }

  function downloadAgentScript() {
    const serverUrl = window.location.origin;
    const hostname = enrolled.device.hostname;
    const apiKey = enrolled.apiKey;

    // Generate a shell script that sets up the agent config
    const script = `#!/bin/bash
# Agent setup script for ${hostname}
# Generated by Remote Lockdown Admin on ${new Date().toISOString()}
#
# Usage: Run this script on the target device alongside the lockdown-agent binary.
#   1. Copy lockdown-agent binary to the target device
#   2. Copy this script to the same directory
#   3. Run: chmod +x agent-setup.sh && ./agent-setup.sh

set -e

CONFIG_DIR="/etc/lockdown-agent"
CONFIG_FILE="$CONFIG_DIR/agent-config.json"
AGENT_BIN="$(dirname "$0")/lockdown-agent"

echo "=== Remote Lockdown Agent Setup ==="
echo "Device: ${hostname}"
echo "Server: ${serverUrl}"
echo ""

# Create config directory
sudo mkdir -p "$CONFIG_DIR"
sudo chmod 700 "$CONFIG_DIR"

# Write agent config
sudo tee "$CONFIG_FILE" > /dev/null << 'AGENT_CONFIG_EOF'
{
  "server_url": "${serverUrl}",
  "device_hostname": "${hostname}",
  "api_key": "${apiKey}",
  "poll_interval": 30,
  "sign_requests": true,
  "server_supports_ack_dedup": true,
  "boot_lock_enabled": true
}
AGENT_CONFIG_EOF

sudo chmod 600 "$CONFIG_FILE"
sudo chown root:root "$CONFIG_FILE"

echo "Config written to $CONFIG_FILE"
echo ""

# Verify agent binary exists
if [ ! -f "$AGENT_BIN" ]; then
    echo "WARNING: lockdown-agent binary not found at $AGENT_BIN"
    echo "         Place the binary in the same directory as this script."
    echo "         You can still start the agent manually with:"
    echo "         lockdown-agent --config $CONFIG_FILE"
else
    echo "Agent binary found: $AGENT_BIN"
    echo "Starting agent..."
    sudo "$AGENT_BIN" --config "$CONFIG_FILE" &
    echo "Agent started in background (PID: $!)"
fi

echo ""
echo "Next steps:"
echo "  - Verify checkin in the admin dashboard"
echo "  - For production: install as a systemd service"
echo ""
echo "Done!"
`;

    const blob = new Blob([script], { type: 'text/x-shellscript' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `agent-setup-${hostname.toLowerCase().replace(/[^a-z0-9]/g, '-')}.sh`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success('Setup script downloaded');
  }

  async function downloadAgentInstaller(platform) {
    setDownloadingInstaller(true);
    try {
      const response = await api.get(`/installer/${enrolled.device.id}?platform=${platform}`, {
        responseType: 'blob',
      });
      const blob = new Blob([response.data], { type: 'application/zip' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `lockdown-agent-${enrolled.device.hostname.toLowerCase().replace(/[^a-z0-9]/g, '-')}-${platform}.zip`;
      a.click();
      URL.revokeObjectURL(url);
      toast.success(`Agent installer (${platform}) downloaded — contains binary, config, and install script`);
    } catch (err) {
      const msg = err.response?.data?.error || err.message || 'Installer download failed';
      // If the response is a blob (error JSON), parse it
      if (err.response?.data instanceof Blob) {
        try {
          const text = await err.response.data.text();
          const parsed = JSON.parse(text);
          toast.error(parsed.error || 'Installer download failed');
        } catch {
          toast.error('Installer download failed');
        }
      } else {
        toast.error(msg);
      }
    } finally {
      setDownloadingInstaller(false);
    }
  }

  async function downloadOneClickInstaller() {
    setDownloadingInstaller(true);
    try {
      const response = await api.get(`/installer/${enrolled.device.id}/nsis`, {
        responseType: 'blob',
      });
      const blob = new Blob([response.data], { type: 'application/vnd.microsoft.portable-executable' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `LockdownAgent-Setup-${enrolled.device.hostname.toLowerCase().replace(/[^a-z0-9]/g, '-')}.exe`;
      a.click();
      URL.revokeObjectURL(url);
      toast.success('One-click installer downloaded — just double-click the .exe on the target device');
    } catch (err) {
      const msg = err.response?.data?.error || err.message || 'Installer download failed';
      if (err.response?.data instanceof Blob) {
        try {
          const text = await err.response.data.text();
          const parsed = JSON.parse(text);
          toast.error(parsed.error || 'Installer download failed');
        } catch {
          toast.error('Installer download failed');
        }
      } else {
        toast.error(msg);
      }
    } finally {
      setDownloadingInstaller(false);
    }
  }

  // --- Enrollment success view ---
  if (enrolled) {
    return (
      <div className="max-w-2xl">
        <button
          onClick={() => navigate('/devices')}
          className="flex items-center gap-2 text-slate-400 hover:text-slate-200 text-sm mb-6"
        >
          <ArrowLeft size={14} /> Back to Devices
        </button>

        <h1 className="text-2xl font-bold text-slate-100 mb-2">Device Enrolled</h1>
        <p className="text-slate-400 text-sm mb-6">
          Configure the agent on the target device using the details below.
        </p>

        {/* Security warning */}
        <div className="card mb-6 border-amber-500/20 bg-amber-950/20">
          <div className="flex gap-3">
            <AlertTriangle className="text-amber-400 shrink-0 mt-0.5" size={18} />
            <div className="text-sm text-amber-200/80">
              <p className="font-medium text-amber-300 mb-1">Save your API key now</p>
              <p>The API key is shown only once. Store it securely — you'll need it to configure the agent on the target device.</p>
            </div>
          </div>
        </div>

        {/* Device details */}
        <div className="card mb-6">
          <h3 className="text-sm font-medium text-slate-300 mb-4">Device Information</h3>
          <div className="space-y-3">
            <div className="flex justify-between items-center">
              <span className="text-xs text-slate-500">Hostname</span>
              <span className="text-sm font-mono text-slate-200">{enrolled.device.hostname}</span>
            </div>
            <div className="flex justify-between items-center">
              <span className="text-xs text-slate-500">Owner</span>
              <span className="text-sm text-slate-200">{enrolled.device.owner_name}</span>
            </div>
            <div className="flex justify-between items-center">
              <span className="text-xs text-slate-500">Device ID</span>
              <span className="text-sm font-mono text-slate-400">{enrolled.device.id}</span>
            </div>
            <div className="flex justify-between items-center">
              <span className="text-xs text-slate-500">Status</span>
              <span className="text-sm text-emerald-400">{enrolled.device.status}</span>
            </div>
          </div>
        </div>

        {/* API key */}
        <div className="card mb-6">
          <div className="flex items-center justify-between mb-3">
            <h3 className="text-sm font-medium text-slate-300 flex items-center gap-2">
              <Key size={14} /> API Key
            </h3>
            <button
              onClick={copyApiKey}
              className="text-xs text-indigo-400 hover:text-indigo-300 flex items-center gap-1"
            >
              {copied ? <Check size={12} /> : <Copy size={12} />}
              {copied ? 'Copied!' : 'Copy'}
            </button>
          </div>
          <code className="block bg-slate-950/50 rounded-lg p-3 text-xs font-mono text-slate-300 break-all">
            {enrolled.apiKey}
          </code>
        </div>

        {/* Download options */}
        <div className="card mb-6">
          <h3 className="text-sm font-medium text-slate-300 mb-4">Agent Configuration</h3>
          <p className="text-xs text-slate-500 mb-4">
            Download a pre-configured file to set up the agent on the target device.
          </p>
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            <button
              onClick={downloadAgentConfig}
              className="flex items-center gap-2 px-4 py-3 rounded-lg bg-slate-800 hover:bg-slate-700 border border-slate-700 text-sm text-slate-200 transition-colors"
            >
              <Download size={16} className="text-indigo-400" />
              <div className="text-left">
                <div className="font-medium">Config JSON</div>
                <div className="text-xs text-slate-500">For manual setup</div>
              </div>
            </button>
            <button
              onClick={downloadAgentScript}
              className="flex items-center gap-2 px-4 py-3 rounded-lg bg-slate-800 hover:bg-slate-700 border border-slate-700 text-sm text-slate-200 transition-colors"
            >
              <Download size={16} className="text-emerald-400" />
              <div className="text-left">
                <div className="font-medium">Setup Script</div>
                <div className="text-xs text-slate-500">Shell script for Linux/Mac</div>
              </div>
            </button>
          </div>
        </div>

        {/* One-click installer (primary — for non-IT users).
            Not available in serverless mode — the Worker has no
            /installer/:id/nsis endpoint. */}
        {serverless ? (
          <div className="card mb-6 border-slate-700/40">
            <div className="flex items-start gap-3">
              <Cloud size={18} className="text-blue-400/60 shrink-0 mt-0.5" />
              <div className="text-sm text-slate-400">
                <p className="font-medium text-slate-300 mb-1">Installer downloads unavailable</p>
                <p className="text-xs">
                  The serverless backend doesn't serve installer binaries. Use the
                  Config JSON or Setup Script above to configure the agent manually,
                  or connect to the full Express server to download pre-built installers.
                </p>
              </div>
            </div>
          </div>
        ) : (
          <>
            <div className="card mb-6 border-emerald-700/30 bg-emerald-950/10">
              <h3 className="text-sm font-medium text-slate-300 mb-2 flex items-center gap-2">
                <Package size={14} className="text-emerald-400" />
                One-Click Installer (Recommended)
              </h3>
              <p className="text-xs text-slate-500 mb-4">
                Download a single .exe file. The user just double-clicks it and follows the
                wizard — no PowerShell, no ZIP extraction, no command line needed.
              </p>
              <button
                onClick={downloadOneClickInstaller}
                disabled={downloadingInstaller}
                className="w-full flex items-center gap-3 px-4 py-4 rounded-lg bg-emerald-900/30 hover:bg-emerald-900/50 border border-emerald-700/50 text-sm text-slate-200 transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
              >
                <Download size={20} className="text-emerald-400" />
                <div className="text-left">
                  <div className="font-medium">Download Windows Installer (.exe)</div>
                  <div className="text-xs text-slate-500">
                    {downloadingInstaller ? 'Compiling installer... (this takes a few seconds)' : 'GUI wizard — just double-click on the target device'}
                  </div>
                </div>
              </button>
            </div>

            {/* Advanced installer options (ZIP — for IT admins) */}
            <div className="card mb-6">
              <h3 className="text-sm font-medium text-slate-300 mb-2">Advanced: ZIP Installer</h3>
              <p className="text-xs text-slate-500 mb-4">
                For IT administrators who prefer manual installation. Contains the raw binary,
                config, and install script in a ZIP file.
              </p>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                <button
                  onClick={() => downloadAgentInstaller('win')}
                  disabled={downloadingInstaller}
                  className="flex items-center gap-2 px-4 py-3 rounded-lg bg-slate-800 hover:bg-slate-700 border border-slate-700 text-sm text-slate-200 transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
                >
                  <Package size={16} className="text-indigo-400" />
                  <div className="text-left">
                    <div className="font-medium">Windows ZIP</div>
                    <div className="text-xs text-slate-500">.exe + install.ps1</div>
                  </div>
                </button>
                <button
                  onClick={() => downloadAgentInstaller('linux')}
                  disabled={downloadingInstaller}
                  className="flex items-center gap-2 px-4 py-3 rounded-lg bg-slate-800 hover:bg-slate-700 border border-slate-700 text-sm text-slate-200 transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
                >
                  <Package size={16} className="text-indigo-400" />
                  <div className="text-left">
                    <div className="font-medium">Linux ZIP</div>
                    <div className="text-xs text-slate-500">binary + install.sh</div>
                  </div>
                </button>
              </div>
              <p className="text-xs text-amber-500/60 mt-3">
                Note: Each installer download generates a new API key for this device. The old key will stop working.
              </p>
            </div>
          </>
        )}

        {/* Actions */}
        <div className="flex gap-3">
          <button
            onClick={() => navigate(`/devices/${enrolled.device.id}`)}
            className="btn-primary flex-1 justify-center"
          >
            View Device Details
          </button>
          <button
            onClick={() => {
              setEnrolled(null);
              setForm({ hostname: '', owner_name: '' });
            }}
            className="btn-secondary flex-1 justify-center"
          >
            Enroll Another Device
          </button>
        </div>
      </div>
    );
  }

  // --- Enrollment form ---
  return (
    <div className="max-w-lg">
      <button
        onClick={() => navigate('/devices')}
        className="flex items-center gap-2 text-slate-400 hover:text-slate-200 text-sm mb-6"
      >
        <ArrowLeft size={14} /> Back to Devices
      </button>

      <h1 className="text-2xl font-bold text-slate-100 mb-1">Enroll a Device</h1>
      <p className="text-slate-400 text-sm mb-6">
        Register a new device in the system. After enrollment, you'll receive an API key to configure the agent.
      </p>

      <form onSubmit={handleSubmit} className="card space-y-4">
        <div>
          <label className="block text-xs font-medium text-slate-400 mb-1">Hostname</label>
          <input
            className="input font-mono"
            value={form.hostname}
            onChange={(e) => setForm({ ...form, hostname: e.target.value })}
            placeholder="e.g. AGENT-LAPTOP-001"
            required
          />
          <p className="text-xs text-slate-500 mt-1">Must match exactly what the agent reports.</p>
        </div>
        <div>
          <label className="block text-xs font-medium text-slate-400 mb-1">Owner Name</label>
          <input
            className="input"
            value={form.owner_name}
            onChange={(e) => setForm({ ...form, owner_name: e.target.value })}
            placeholder="e.g. John Doe"
            required
          />
        </div>
        <button className="btn-primary" type="submit" disabled={loading}>
          {loading ? 'Enrolling...' : 'Enroll Device'}
        </button>
      </form>
    </div>
  );
}
