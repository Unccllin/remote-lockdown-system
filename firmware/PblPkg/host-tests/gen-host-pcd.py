#!/usr/bin/env python3
"""Generate the host view of PblPkg's PCDs from the real `PblPkg.dec`.

The host tests assert on bytes that depend on PCD defaults: which TPM hierarchy
`PblTpmNvDefineSpace` authorizes with, whether parameter encryption is on, the NV index
base, and the NV auth value's length. Hardcoding those in the harness would let a PCD
default change in `PblPkg.dec` pass unnoticed — the exact drift class `extract-decls.py`
exists to prevent for the structs. So the defaults are parsed out of the .dec at build
time and emitted as `HOST_PCD_<Name>` constants that the host shim's `FixedPcdGet*`
maps onto.

Types handled (`PblPkg.dec` uses only these): UINT8, UINT32, BOOLEAN, VOID*.

Usage: gen-host-pcd.py <PblPkg.dec> > pbl_pcd.generated.h
"""

import re
import sys

# gPblPkgTokenSpaceGuid.PcdName|value|TYPE|token
PCD_LINE = re.compile(
    r"^\s*gPblPkgTokenSpaceGuid\.([A-Za-z0-9_]+)\s*\|\s*(.*?)\s*\|\s*([A-Za-z0-9_*]+)\s*\|"
)


def render(name: str, value: str, kind: str) -> str:
    """Return one `HOST_PCD_<name>` definition appropriate to its PCD type."""
    if kind == "BOOLEAN":
        if value not in ("TRUE", "FALSE"):
            raise SystemExit(f"gen-host-pcd: {name}: BOOLEAN PCD with value {value!r}")
        return f"#define HOST_PCD_{name}  ((BOOLEAN){value})"
    if kind in ("UINT8", "UINT16", "UINT32", "UINT64"):
        width = {"UINT8": "UINT8", "UINT16": "UINT16", "UINT32": "UINT32", "UINT64": "UINT64"}[kind]
        return f"#define HOST_PCD_{name}  (({width})({value}))"
    if kind == "VOID*":
        # EDK II's generated AutoGen gives a string VOID* PCD a NUL-terminated CHAR8 array
        # whose *size* includes the NUL (verified against the firmware build's AutoGen.c:
        # PcdPblTpmNvAuthValue is `const UINT8 [...][31]` with Size 31 for a 30-char
        # string). An array here reproduces both the pointer and the size exactly.
        if not (value.startswith('"') and value.endswith('"')):
            raise SystemExit(f"gen-host-pcd: {name}: VOID* PCD that is not a string: {value!r}")
        # A bare string literal rather than a file-scope array: a `static const CHAR8[]`
        # in a header trips -Wunused-const-variable under -Werror in any TU that does not
        # reference it. The size macro reproduces FixedPcdGetSize exactly (literal size,
        # so the NUL counts).
        return (
            f"#define HOST_PCD_{name}  ((CONST CHAR8 *){value})\n"
            f"#define HOST_PCD_{name}_SIZE  ((UINTN)(sizeof({value})))"
        )
    raise SystemExit(f"gen-host-pcd: {name}: unsupported PCD type {kind!r}")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding="utf-8") as handle:
        lines = handle.read().splitlines()

    out = [
        "/* GENERATED by host-tests/gen-host-pcd.py from ../../PblPkg.dec — do not edit. */",
        "#ifndef PBL_PCD_GENERATED_H",
        "#define PBL_PCD_GENERATED_H",
        "",
    ]
    count = 0
    for line in lines:
        m = PCD_LINE.match(line)
        if not m:
            continue
        out.append(render(m.group(1), m.group(2), m.group(3)))
        count += 1

    if count == 0:
        raise SystemExit("gen-host-pcd: parsed no PCDs from PblPkg.dec — format changed?")

    out += ["", f"/* {count} PCDs */", "#endif /* PBL_PCD_GENERATED_H */"]
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
