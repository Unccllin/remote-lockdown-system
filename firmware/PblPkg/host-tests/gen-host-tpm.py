#!/usr/bin/env python3
"""Fold the vendored EDK II TPM headers into one self-contained header for the host build.

`include/IndustryStandard/{Tpm12,Tpm20}.h` are verbatim copies of MdePkg's, kept byte-identical
so `run-host-tests.sh` can `cmp` them against the EDK II checkout. That fidelity costs one
thing: `Tpm20.h` does `#include <IndustryStandard/Tpm12.h>`, an *angled* include that only
resolves if the whole `MdePkg/Include` tree is on the search path — which is true in the
firmware build and false for a host build that vendors two files.

Rather than hand-edit an upstream file (defeating the `cmp`) or thread a second include root
through every consumer, this script emits the pair as ONE generated header with the nested
include line dropped:

  * the transformation is mechanical — nothing is transcribed by hand, so there is no
    place for a wrong constant to enter;
  * the originals stay verbatim, so the drift check keeps working;
  * the result is self-contained, so the host shim needs no include-path cooperation and an
    isolated header analysis sees the same declarations the compiler does.

Usage: gen-host-tpm.py <Tpm12.h> <Tpm20.h> > pbl_tpm_wire.generated.h
"""

import re
import sys

NESTED_INCLUDE = re.compile(r"^\s*#\s*include\s*<IndustryStandard/Tpm12\.h>\s*$", re.M)


def strip_nested_include(source: str, name: str) -> str:
    """Remove the `#include <IndustryStandard/Tpm12.h>` line, replacing it with a note."""
    replaced, count = NESTED_INCLUDE.subn(
        "/* [gen-host-tpm] nested `#include <IndustryStandard/Tpm12.h>` removed: Tpm12.h is "
        "concatenated above in this file. */",
        source,
    )
    if count != 1:
        raise SystemExit(
            f"gen-host-tpm: {name}: expected exactly one nested Tpm12.h include, found {count}.\n"
            "  Upstream changed its include structure — re-check how the pair must be combined."
        )
    return replaced


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2

    with open(sys.argv[1], encoding="utf-8") as handle:
        tpm12 = handle.read()
    with open(sys.argv[2], encoding="utf-8") as handle:
        tpm20 = strip_nested_include(handle.read(), sys.argv[2])

    # Tpm12.h first: Tpm20.h's declarations build on its legacy types, and both files open
    # with `#pragma once`, which is harmless when they are concatenated.
    #
    # A real macro guard wraps the result. `#pragma once` cannot help here: the same
    # declarations arrive twice through DIFFERENT physical files (this fold and Tpm20.h's own
    # `#include <IndustryStandard/Tpm12.h>`), and `#pragma once` only dedupes one file. Without
    # the guard the build fails with "redefinition of struct tdTPM_STRUCT_VER".
    print("/* GENERATED by host-tests/gen-host-tpm.py from the vendored EDK II TPM headers.")
    print("   Do not edit: the sources are verbatim MdePkg copies, drift-checked by cmp. */")
    print("#ifndef PBL_TPM_WIRE_GENERATED_H")
    print("#define PBL_TPM_WIRE_GENERATED_H")
    print("")
    print(tpm12.rstrip())
    print("")
    print(tpm20.rstrip())
    print("")
    print("#endif /* PBL_TPM_WIRE_GENERATED_H */")
    return 0


if __name__ == "__main__":
    sys.exit(main())
