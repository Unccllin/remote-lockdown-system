def write_config(
    server_url: str, api_key: str, hostname: str, device_id: str, boot_lock_enabled: bool = True
) -> Path:
    """Write the agent config.json to the install directory."""

    config = {
        "server_url": server_url.rstrip("/"),
        "api_key": api_key,
        "hostname": hostname,
        "device_id": device_id,
        "poll_interval": 30,
        "lockdown_folder": str(LOCKDOWN_FOLDER),
        "lock_sentinel": str(INSTALL_DIR / ".locked"),
        "pending_ack_file": str(INSTALL_DIR / ".pending_ack"),
        "recovery_key_file": str(INSTALL_DIR / ".recovery_key"),
        "boot_lock_enabled": boot_lock_enabled,
        "verify_tls": True,
        "server_supports_ack_dedup": True,
    }

    print_step(2, f"Writing config to {CONFIG_FILE}...")
    INSTALL_DIR.mkdir(parents=True, exist_ok=True)
    CONFIG_FILE.write_text(json.dumps(config, indent=2))
    print_ok("Config written")
    return CONFIG_FILE


# ---------------------------------------------------------------------------
# File installation
# ---------------------------------------------------------------------------


def install_files(agent_exe: Path) -> Path:
    """Copy the agent exe to the install directory."""

    print_step(3, f"Installing agent to {INSTALL_DIR}...")
    INSTALL_DIR.mkdir(parents=True, exist_ok=True)

    dest = INSTALL_DIR / AGENT_EXE_NAME
    if agent_exe.resolve() == dest.resolve():
        print_ok("Agent already in install location")
        return dest

    shutil.copy2(agent_exe, dest)
    print_ok(f"Agent copied: {dest}")
    return dest


def create_lockdown_folder():
    """Create the lockdown folder with a test file."""
    print_step(4, f"Creating lockdown folder: {LOCKDOWN_FOLDER}...")
    LOCKDOWN_FOLDER.mkdir(parents=True, exist_ok=True)

    # Create a test file so encryption has something to encrypt
    test_file = LOCKDOWN_FOLDER / "README.txt"
    if not test_file.exists():
        test_file.write_text(
            "This device is protected by Remote Lockdown System.\n"
            "If you see this file encrypted, the device has been flagged as stolen.\n"
            "Contact your administrator to recover access.\n"
        )
    print_ok("Lockdown folder ready")


# ---------------------------------------------------------------------------
# Service installation
# ---------------------------------------------------------------------------


def install_service():
    """Install the scheduled task watchdog via service_installer."""

    print_step(5, "Installing service (scheduled task + registry watchdog)...")
    try:
        import service_installer

        success = service_installer.install()
        if success:
            print_ok("Service installed — agent will auto-restart if killed")
        else:
            print_fail("Service installation failed — agent will not persist after reboot")
        return success
    except ImportError:
        print_warn("service_installer module not found — skipping service install")
        return False
    except (subprocess.SubprocessError, OSError, RuntimeError) as e:
        print_fail(f"Service installation error: {e}")
        return False


# ---------------------------------------------------------------------------
# Verification
# ---------------------------------------------------------------------------


def verify_checkin(server_url: str, api_key: str) -> bool:
    """Verify the agent can check in to the server."""

    print_step(6, "Verifying agent can reach server...")
    try:
        # Simple health check
        resp = requests.get(
            f"{server_url.rstrip('/')}/api/health",
            timeout=10,
            verify=True,
        )
        if resp.status_code == 200:
            data = resp.json()
            print_ok(f"Server reachable: status={data.get('status', 'ok')}")
            return True
        else:
            print_fail(f"Server health check failed: HTTP {resp.status_code}")
            return False
    except (requests.RequestException, json.JSONDecodeError, ValueError, OSError) as e:
        print_fail(f"Cannot reach server: {e}")
        return False


# ---------------------------------------------------------------------------
# Interactive prompts
