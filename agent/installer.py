# Colors for console output.
# enabling ANSI on Windows 10+ used to be done with os.system(""), which spawns a
# shell to do nothing. Set the console mode directly instead — same result, no
# shell execution and no process spawned on non-Windows hosts.


def _enable_windows_ansi() -> None:
    """Turn on virtual-terminal processing for this process's stdout."""
    if platform.system() != "Windows":
        return
    kernel32 = getattr(ctypes, "kernel32", None)
    if kernel32 is None:
        return
    try:
        std_output_handle = -11
        enable_virtual_terminal_processing = 0x0004
        handle = kernel32.GetStdHandle(std_output_handle)
        mode = ctypes.c_uint32()
        if not kernel32.GetConsoleMode(handle, ctypes.byref(mode)):
            return  # no console (windowed build) — nothing to configure
        kernel32.SetConsoleMode(handle, mode.value | enable_virtual_terminal_processing)
    except (AttributeError, OSError):
        return


_enable_windows_ansi()

