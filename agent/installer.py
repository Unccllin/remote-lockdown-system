def install_service():
    """Install the scheduled task watchdog via service_installer."""

    print_step(5, "Installing service (scheduled task + registry watchdog)...")
    try:
        import service_installer

        success = service_installer.install()
        if success:
            print_ok("Service installed — agent will auto-restart if killed")
        else:
            print_fail("Service installation failed — agent will not persist after reboot")
        return success
    except ImportError:
        print_warn("service_installer module not found — skipping service install")
        return False
    except (subprocess.SubprocessError, OSError, RuntimeError) as e:
        print_fail(f"Service installation error: {e}")
        return False


