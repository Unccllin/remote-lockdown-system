def print_summary(config_path: Path, agent_path: Path, device_id: str, hostname: str):
    print(f"\n{BOLD}{GREEN}  ✓ Installation Complete{RESET}\n")
    print(f"  {BOLD}Device ID:{RESET}    {device_id}")
    print(f"  {BOLD}Hostname:{RESET}     {hostname}")
    print(f"  {BOLD}Config:{RESET}       {config_path}")
    print(f"  {BOLD}Agent:{RESET}        {agent_path}")
    print(f"  {BOLD}Lockdown:{RESET}     {LOCKDOWN_FOLDER}")
    print(f"\n  {DIM}The agent is now running in the background and will")
    print("  auto-restart if killed. To manage this device, open the")
    print(f"  admin dashboard and flag it as stolen to trigger lockdown.{RESET}\n")


