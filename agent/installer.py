#!/usr/bin/env python3
"""
One-Click Agent Installer
-------------------------
A single exe that an operator runs on a target device to:

  1. Enroll the device with the server (POST /api/enroll)
  2. Generate config.json with the returned API key
  3. Copy the agent exe to C:\\ProgramData\\LockdownAgent\\
  4. Install the scheduled task watchdog (service_installer.install)
  5. Launch the agent immediately

The operator only needs to provide:
  - Server URL (pre-filled with the Cloudflare Worker URL)
  - Admin token (for enrollment authorization)
  - Owner name (for device registration)

Usage (interactive):
    lockdown-installer.exe

Usage (silent — for scripted deployment):
    lockdown-installer.exe --server-url https://... --admin-token XXX --owner "Company"

Usage (enrollment token — streamlined flow):
    lockdown-installer.exe --server-url https://... --token ENROLL_TOKEN

The enrollment token is generated by the admin dashboard (POST /api/enroll/token)
and is valid for 15 minutes. It replaces the admin token so the operator never
needs to enter the admin password on the target machine.

The installer must be run as Administrator (the service installer needs
admin to create scheduled tasks with SYSTEM privileges).

Built with PyInstaller:
    py -m PyInstaller --onefile --name lockdown-installer \
        --hidden-import service_installer \
        --hidden-import tamper_protection \
        --hidden-import cryptography.fernet \
        installer.py
"""

from __future__ import annotations

import argparse
import ctypes
import json
import os
import platform
import shutil
import socket
import subprocess
import sys
from pathlib import Path

import requests

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

DEFAULT_SERVER_URL = "https://lockdown-serverless.mainacollins196.workers.dev"
INSTALL_DIR = Path(os.environ.get("PROGRAMDATA", "C:\\ProgramData")) / "LockdownAgent"
CONFIG_FILE = INSTALL_DIR / "config.json"
AGENT_EXE_NAME = "lockdown-agent.exe"
INSTALLER_EXE_NAME = "lockdown-installer.exe"
LOCKDOWN_FOLDER = INSTALL_DIR / "lockdown_folder"

# Colors for console output
if platform.system() == "Windows":
    os.system("")  # noqa: S605 — Enable ANSI escape sequences on Windows 10+

BOLD = "\033[1m"
GREEN = "\033[92m"
YELLOW = "\033[93m"
RED = "\033[91m"
BLUE = "\033[94m"
RESET = "\033[0m"
DIM = "\033[2m"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def print_banner():
    print(f"\n{BOLD}{BLUE}  Remote Lockdown System — Agent Installer{RESET}")
    print(f"{DIM}  One-click enrollment + service installation{RESET}\n")


def print_step(num: int, msg: str):
    print(f"  {BOLD}[{num}]{RESET} {msg}")


def print_ok(msg: str = ""):
    print(f"  {GREEN}✓{RESET} {msg}")


def print_fail(msg: str = ""):
    print(f"  {RED}✗{RESET} {msg}")


def print_warn(msg: str = ""):
    print(f"  {YELLOW}⚠{RESET} {msg}")


def is_admin() -> bool:
    if platform.system() != "Windows":
        return False
    try:
        return bool(ctypes.windll.shell32.IsUserAnAdmin())
    except (OSError, AttributeError, PermissionError):
        return False


def get_hostname() -> str:
    try:
        return socket.gethostname()
    except OSError:
        return "UNKNOWN"


def get_mac_address() -> str:
    """Get the primary MAC address."""
    try:
        import uuid

        mac = uuid.getnode()
        return ":".join(f"{(mac >> ele) & 0xFF:02X}" for ele in range(40, -1, -8))
    except (OSError, AttributeError, ValueError):
        return None


def get_hardware_uuid() -> str:
    """Get the hardware UUID from WMI."""
    if platform.system() != "Windows":
        return None
    try:
        result = subprocess.run(
            [
                "powershell",
                "-NoProfile",
                "-Command",
                "(Get-WmiObject Win32_ComputerSystemProduct).UUID",
            ],
            capture_output=True,
            text=True,
            timeout=10,
        )
        uuid = result.stdout.strip()
        if uuid and uuid != "00000000-0000-0000-0000-000000000000":
            return uuid
    except Exception:  # noqa: S110 — WMI not available on non-Windows / older builds
        pass
    return None


def get_serial_number() -> str:
    """Get the machine serial number (service tag).

    Uses the platform-appropriate source:
      - Windows: WMI/CIM Win32_BIOS SerialNumber
      - Linux:   /sys/class/dmi/id/product_serial
      - macOS:   IOPlatformSerialNumber via ioreg

    Returns None if the serial number is not available.
    """
    system = platform.system()
    try:
        if system == "Windows":
            result = subprocess.run(
                [
                    "powershell",
                    "-NoProfile",
                    "-Command",
                    "Get-CimInstance Win32_BIOS | Select-Object -ExpandProperty SerialNumber",
                ],
                capture_output=True,
                text=True,
                timeout=10,
            )
            serial = result.stdout.strip()
            invalid = {"none", "default string", "to be filled by o.e.m."}
            if serial and serial.lower() not in invalid:
                return serial
        elif system == "Linux":
            try:
                serial = Path("/sys/class/dmi/id/product_serial").read_text().strip()
            except (FileNotFoundError, PermissionError):
                return None
            if serial and serial.lower() not in ("none", "0", "default string"):
                return serial
        elif system == "Darwin":
            result = subprocess.run(
                [
                    "ioreg",
                    "-rd1",
                    "-c",
                    "IOPlatformExpertDevice",
                ],
                capture_output=True,
                text=True,
                timeout=10,
            )
            for line in result.stdout.splitlines():
                if "IOPlatformSerialNumber" in line:
                    # "IOPlatformSerialNumber" = "C02XXXXXXXX"
                    parts = line.split('"')
                    if len(parts) >= 4:
                        serial = parts[-2].strip()
                        if serial:
                            return serial
    except Exception:  # noqa: S110 — serial not available on this platform / build
        pass
    return None


def find_agent_exe() -> Path | None:
    """Find the agent exe to install. Look next to the installer, then in cwd."""
    if getattr(sys, "frozen", False):
        exe_dir = Path(sys.executable).parent
    else:
        exe_dir = Path(__file__).parent
    candidates = [
        exe_dir / AGENT_EXE_NAME,
        Path.cwd() / AGENT_EXE_NAME,
    ]
    for c in candidates:
        if c.exists():
            return c
    return None


