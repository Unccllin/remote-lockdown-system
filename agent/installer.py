def enroll_device(server_url: str, admin_token: str, hostname: str, owner_name: str) -> dict:
    """Enroll the device via the server API.

    Returns: {"device": {...}, "api_key": "..."} or raises Exception.
    """
    url = f"{server_url.rstrip('/')}/api/enroll"
    hardware_uuid = get_hardware_uuid()
    mac_address = get_mac_address()
    serial_number = get_serial_number()
    payload = {
        "hostname": hostname,
        "owner_name": owner_name,
        "hardware_uuid": hardware_uuid,
        "mac_address": mac_address,
        "serial_number": serial_number,
    }
    headers = {
        "Content-Type": "application/json",
        "Authorization": f"Bearer {admin_token}",
    }

    print_step(1, f"Enrolling device '{hostname}' with server...")
    print(f"      {DIM}POST {url}{RESET}")

    try:
        resp = requests.post(url, json=payload, headers=headers, timeout=30, verify=True)
    except requests.exceptions.ConnectionError as e:
        raise Exception(f"Cannot reach server: {e}")
    except requests.exceptions.Timeout:
        raise Exception("Server did not respond within 30 seconds")

    if resp.status_code == 401:
        raise Exception("Admin token rejected — check the token and try again")
    if resp.status_code == 409:
        raise Exception(f"Device '{hostname}' is already enrolled on this server")
    if resp.status_code != 201:
        raise Exception(f"Enrollment failed (HTTP {resp.status_code}): {resp.text}")

    data = resp.json()
    print_ok(f"Device enrolled: id={data['device']['id']}")
    print(f"      Hardware UUID: {hardware_uuid or 'N/A'}")
    print(f"      Serial Number: {serial_number or 'N/A'}")
    print(f"      MAC Address: {mac_address or 'N/A'}")
    return data


def enroll_device_with_token(server_url: str, token: str, hostname: str, owner_name: str) -> dict:
    """Enroll the device using an enrollment token (POST /api/enroll/claim).

    This is the streamlined flow: the admin generates a short-lived token in
    the dashboard, and the installer uses it instead of an admin password.
    No admin token is required.

    Returns: {"device": {...}, "api_key": "..."} or raises Exception.
    """
    url = f"{server_url.rstrip('/')}/api/enroll/claim"
    hardware_uuid = get_hardware_uuid()
    mac_address = get_mac_address()
    serial_number = get_serial_number()
    payload = {
        "token": token,
        "hostname": hostname,
        "owner_name": owner_name,
        "hardware_uuid": hardware_uuid,
        "mac_address": mac_address,
        "serial_number": serial_number,
    }
    headers = {
        "Content-Type": "application/json",
    }

    print_step(1, f"Enrolling device '{hostname}' with enrollment token...")
    print(f"      {DIM}POST {url}{RESET}")

    try:
        resp = requests.post(url, json=payload, headers=headers, timeout=30, verify=True)
    except requests.exceptions.ConnectionError as e:
        raise Exception(f"Cannot reach server: {e}")
    except requests.exceptions.Timeout:
        raise Exception("Server did not respond within 30 seconds")

    if resp.status_code == 401:
        body = ""
        try:
            body = resp.json().get("error", "")
        except (ValueError, KeyError):
            pass
        if "expired" in body.lower():
            raise Exception("Enrollment token has expired — ask the admin to generate a new one")
        raise Exception("Enrollment token rejected — it may be invalid or already used")
    if resp.status_code == 409:
        raise Exception(f"Device '{hostname}' is already enrolled on this server")
    if resp.status_code != 201:
        raise Exception(f"Enrollment failed (HTTP {resp.status_code}): {resp.text}")

    data = resp.json()
    print_ok(f"Device enrolled: id={data['device']['id']}")
    print(f"      Hardware UUID: {hardware_uuid or 'N/A'}")
    print(f"      Serial Number: {serial_number or 'N/A'}")
    print(f"      MAC Address: {mac_address or 'N/A'}")
    return data


