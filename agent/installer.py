def verify_checkin(server_url: str, api_key: str) -> bool:
    """Verify the agent can check in to the server."""

    print_step(6, "Verifying agent can reach server...")
    try:
        # Simple health check
        resp = requests.get(
            f"{server_url.rstrip('/')}/api/health",
            timeout=10,
            verify=True,
        )
        if resp.status_code == 200:
            data = resp.json()
            print_ok(f"Server reachable: status={data.get('status', 'ok')}")
            return True
        else:
            print_fail(f"Server health check failed: HTTP {resp.status_code}")
            return False
    except (requests.RequestException, json.JSONDecodeError, ValueError, OSError) as e:
        print_fail(f"Cannot reach server: {e}")
        return False


