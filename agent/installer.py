def is_admin() -> bool:
    if platform.system() != "Windows":
        return False
    # ctypes.windll only exists on Windows; the platform check above is the real
    # guard, but the attribute lookup is done reflectively so type checkers and
    # non-Windows imports do not trip over it.
    windll = getattr(ctypes, "windll", None)
    if windll is None:
        return False
    try:
        return bool(windll.shell32.IsUserAnAdmin())
    except (OSError, AttributeError, PermissionError):
        return False


def get_hostname() -> str:
    try:
        return socket.gethostname()
    except OSError:
        return "UNKNOWN"


def get_mac_address() -> str | None:
    """Get the primary MAC address."""
    try:
        import uuid

        mac = uuid.getnode()
        return ":".join(f"{(mac >> ele) & 0xFF:02X}" for ele in range(40, -1, -8))
    except (OSError, AttributeError, ValueError):
        return None


def get_hardware_uuid() -> str | None:
    """Get the hardware UUID from WMI."""
    if platform.system() != "Windows":
        return None
    try:
        result = subprocess.run(
            [
                "powershell",
                "-NoProfile",
                "-Command",
                "(Get-WmiObject Win32_ComputerSystemProduct).UUID",
            ],
            capture_output=True,
            text=True,
            timeout=10,
        )
        uuid = result.stdout.strip()
        if uuid and uuid != "00000000-0000-0000-0000-000000000000":
            return uuid
    except Exception:  # noqa: S110 — WMI not available on non-Windows / older builds
        pass
    return None


def get_serial_number() -> str | None:
    """Get the machine serial number (service tag).

    Uses the platform-appropriate source:
      - Windows: WMI/CIM Win32_BIOS SerialNumber
      - Linux:   /sys/class/dmi/id/product_serial
      - macOS:   IOPlatformSerialNumber via ioreg

    Returns None if the serial number is not available.
    """
    system = platform.system()
    try:
        if system == "Windows":
            result = subprocess.run(
                [
                    "powershell",
                    "-NoProfile",
                    "-Command",
                    "Get-CimInstance Win32_BIOS | Select-Object -ExpandProperty SerialNumber",
                ],
                capture_output=True,
                text=True,
                timeout=10,
            )
            serial = result.stdout.strip()
            invalid = {"none", "default string", "to be filled by o.e.m."}
            if serial and serial.lower() not in invalid:
                return serial
        elif system == "Linux":
            try:
                serial = Path("/sys/class/dmi/id/product_serial").read_text().strip()
            except (FileNotFoundError, PermissionError):
                return None
            if serial and serial.lower() not in ("none", "0", "default string"):
                return serial
        elif system == "Darwin":
            result = subprocess.run(
                [
                    "ioreg",
                    "-rd1",
                    "-c",
                    "IOPlatformExpertDevice",
                ],
                capture_output=True,
                text=True,
                timeout=10,
            )
            for line in result.stdout.splitlines():
                if "IOPlatformSerialNumber" in line:
                    # "IOPlatformSerialNumber" = "C02XXXXXXXX"
                    parts = line.split('"')
                    if len(parts) >= 4:
                        serial = parts[-2].strip()
                        if serial:
                            return serial
    except Exception:  # noqa: S110 — serial not available on this platform / build
        pass
    return None


def find_agent_exe() -> Path | None:
    """Find the agent exe to install. Look next to the installer, then in cwd."""
    if getattr(sys, "frozen", False):
        exe_dir = Path(sys.executable).parent
    else:
        exe_dir = Path(__file__).parent
    candidates = [
        exe_dir / AGENT_EXE_NAME,
        Path.cwd() / AGENT_EXE_NAME,
    ]
    for c in candidates:
        if c.exists():
            return c
    return None


