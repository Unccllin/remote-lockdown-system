def run_uninstall(uninstall_token: str | None) -> int:
    """Remove the agent's persistence after the backend authorizes it.

    Delegates to service_installer.uninstall(), the same function the agent uses
    from the target machine, so there is exactly one removal code path. Returns a
    process exit code (0 = removed).
    """
    print_step(1, "Checking this machine's enrolment...")
    if not CONFIG_FILE.exists():
        print_fail(f"No agent config at {CONFIG_FILE} — nothing is installed here.")
        return 1

    try:
        config = json.loads(CONFIG_FILE.read_text())
    except (OSError, json.JSONDecodeError) as e:
        print_fail(f"Cannot read {CONFIG_FILE}: {e}")
        return 1

    server_url = config.get("server_url")
    api_key = config.get("api_key")
    device_id = config.get("device_id")
    print_ok(f"Device {config.get('hostname', get_hostname())} on {server_url}")

    if not uninstall_token:
        print_fail("An uninstall token is required — removal is authorized by the backend.")
        print(
            f"  {DIM}Request one with POST {server_url}/api/agent/uninstall-auth "
            f"(agent key), then re-run with --uninstall-token <TOKEN>.{RESET}"
        )
        return 1
    if not server_url or not api_key:
        print_fail("config.json has no server_url/api_key — cannot verify the token.")
        return 1

    print_step(2, "Verifying the uninstall token and removing persistence...")
    try:
        import service_installer
    except ImportError:
        print_fail("service_installer module not available in this build.")
        return 1

    try:
        removed = service_installer.uninstall(
            uninstall_token=uninstall_token,
            server_url=server_url,
            api_key=api_key,
            device_id=device_id,
        )
    except (subprocess.SubprocessError, OSError, RuntimeError) as e:
        print_fail(f"Uninstall failed: {e}")
        return 1

    if not removed:
        print_fail("The backend did not authorize this uninstall — nothing was removed.")
        return 1

    print_ok("Persistence removed (scheduled task, run key, tamper protection).")
    print(f"  {DIM}Files in {INSTALL_DIR} can now be deleted.{RESET}\n")
    return 0


