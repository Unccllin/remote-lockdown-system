def main():
    parser = argparse.ArgumentParser(
        description="Remote Lockdown System — One-Click Agent Installer",
    )
    parser.add_argument(
        "--server-url",
        default=None,
        help="Server URL (default: Cloudflare Worker)",
    )
    parser.add_argument(
        "--admin-token",
        default=None,
        help="Admin token for enrollment auth (legacy flow)",
    )
    parser.add_argument(
        "--token",
        default=None,
        help="Enrollment token (streamlined flow — no admin password needed)",
    )
    parser.add_argument(
        "--owner",
        default=None,
        help="Owner name for device registration",
    )
    parser.add_argument(
        "--hostname",
        default=None,
        help="Device hostname (default: machine hostname)",
    )
    parser.add_argument(
        "--no-boot-lock",
        action="store_true",
        help="Disable BCD/UEFI boot lockdown",
    )
    parser.add_argument(
        "--silent",
        action="store_true",
        help="Skip interactive prompts (requires all args)",
    )
    args = parser.parse_args()

    print_banner()

    # --- Check platform ---
    if platform.system() != "Windows":
        print_fail("This installer is for Windows only.")
        sys.exit(1)

    # --- Check admin ---
    if not is_admin():
        print_fail("Administrator privileges required. Right-click → Run as Administrator.")
        print(f"\n  {DIM}Or run from an elevated PowerShell:{RESET}")
        print(f"  {DIM}  Start-Process .\\lockdown-installer.exe -Verb RunAs{RESET}")
        sys.exit(1)

    print_ok("Running as Administrator\n")

    # --- Find agent exe ---
    agent_exe = find_agent_exe()
    if not agent_exe:
        print_fail(f"Cannot find {AGENT_EXE_NAME}. Place it next to this installer.")
        print(f"  {DIM}Expected: {Path(sys.executable).parent / AGENT_EXE_NAME}{RESET}")
        sys.exit(1)
    print_ok(f"Agent found: {agent_exe}\n")

    # --- Get parameters ---
    # The --token flag enables the streamlined enrollment flow: the admin
    # generates a short-lived token in the dashboard, and the installer uses
    # POST /api/enroll/claim instead of POST /api/enroll. No admin password
    # is needed on the target machine.
    use_token_flow = bool(args.token)
    admin_token = args.admin_token

    if args.silent:
        server_url = args.server_url or DEFAULT_SERVER_URL
        admin_token = args.admin_token
        enroll_token = args.token
        owner_name = args.owner or "Auto-enrolled"
        hostname = args.hostname or get_hostname()
        if use_token_flow:
            if not enroll_token:
                print_fail("--silent with --token requires a token value")
                sys.exit(1)
        elif not admin_token:
            print_fail("--silent requires --admin-token or --token")
            sys.exit(1)
    else:
        server_url = prompt_input("Server URL", DEFAULT_SERVER_URL)
        if use_token_flow:
            enroll_token = args.token
            print_ok("Using enrollment token flow (no admin password needed)")
        else:
            enroll_token = None
            admin_token = prompt_secret("Admin token (password)")
        owner_name = prompt_input("Owner name", "Hardware Test")
        hostname = prompt_input("Device hostname", get_hostname())

    if use_token_flow:
        if not enroll_token:
            print_fail("Enrollment token is required")
            sys.exit(1)
    elif not admin_token:
        print_fail("Admin token is required (or use --token for the streamlined flow)")
        sys.exit(1)

    # --- Step 1: Enroll ---
    try:
        if use_token_flow:
            enroll_data = enroll_device_with_token(server_url, enroll_token, hostname, owner_name)
        else:
            enroll_data = enroll_device(server_url, admin_token, hostname, owner_name)
    except Exception as e:  # noqa: BLE001 — enroll functions raise generic Exception for user-facing errors
        print_fail(str(e))
        sys.exit(1)

    device_id = enroll_data["device"]["id"]
    api_key = enroll_data["api_key"]

    # --- Step 2: Write config ---
    boot_lock = not args.no_boot_lock
    write_config(server_url, api_key, hostname, device_id, boot_lock_enabled=boot_lock)

    # --- Step 3: Install files ---
    installed_agent = install_files(agent_exe)

    # --- Step 4: Create lockdown folder ---
    create_lockdown_folder()

    # --- Step 5: Install service ---
    install_service()

    # --- Step 6: Verify connectivity ---
    verify_checkin(server_url, api_key)

    # --- Summary ---
    print_summary(CONFIG_FILE, installed_agent, device_id, hostname)

    print(f"  {DIM}The agent is now running. You can manage this device from the")
    print(f"  dashboard at {server_url}{RESET}\n")


if __name__ == "__main__":
    main()
