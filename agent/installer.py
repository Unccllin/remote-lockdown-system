#!/usr/bin/env python3
"""
One-Click Agent Installer
-------------------------
A single exe that an operator runs on a target device to:

  1. Enroll the device with the server (POST /api/enroll)
  2. Generate config.json with the returned API key
  3. Copy the agent exe to C:\\ProgramData\\LockdownAgent\\
  4. Install the scheduled task watchdog (service_installer.install)
  5. Launch the agent immediately

The operator only needs to provide:
  - Server URL (pre-filled with the Cloudflare Worker URL)
  - Admin token (for enrollment authorization)
  - Owner name (for device registration)

Usage (interactive):
    lockdown-installer.exe

Usage (silent — for scripted deployment):
    lockdown-installer.exe --server-url https://... --admin-token XXX --owner "Company"

Usage (enrollment token — streamlined flow):
    lockdown-installer.exe --server-url https://... --token ENROLL_TOKEN

The enrollment token is generated by the admin dashboard (POST /api/enroll/token)
and is valid for 15 minutes. It replaces the admin token so the operator never
needs to enter the admin password on the target machine.

Usage (authorized removal):
    lockdown-installer.exe --uninstall --uninstall-token TOKEN

Usage (per-device installer — config baked in, no enrolment):
    lockdown-installer.exe --config-file config.json --silent

Per-device installers generated by the dashboard already created the device and
baked its API key into config.json, so nothing is typed on the target machine.
The config is read, normalised through the same build_config() as the enrolment
flow (a generated config used to carry 8 of the 12 keys, so the agent fell back
to different lockdown/state paths), and then installed identically.

Removal is authorized by the backend, not by local admin rights: the token is
requested from POST /api/agent/uninstall-auth and is valid for 5 minutes.
Without it the scheduled task, registry key and tamper-protection DENY ACEs stay
in place — deliberately, because the agent is an anti-theft control and an
uninstall that any local administrator can run would be the bypass it exists to
prevent. The server URL, API key and device id come from the installed
config.json, so nothing has to be re-entered on the target machine.

The installer must be run as Administrator (the service installer needs
admin to create scheduled tasks with SYSTEM privileges).

Built with PyInstaller from agent/installer.spec (which carries the hidden
imports), by agent/build.ps1:
    py -m PyInstaller installer.spec
"""

