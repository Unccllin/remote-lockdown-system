#!/usr/bin/env node
/**
 * generate-policy-root-of-trust.js — Provision the firmware policy signing key
 * root of trust (D-205).
 *
 * Generates a new ES256 (ECDSA P-256) policy signing key, exports the SPKI
 * (SubjectPublicKeyInfo DER), computes the kid (SHA-256 of SPKI), and emits
 * a C header file that PolicyRootOfTrust.c includes.
 *
 * The private key is stored as base64 PKCS8 in a gitignored file
 * (.pbl_policy_signing_key) for server-side use. The public key (SPKI + kid)
 * is embedded in the firmware as a compile-time constant.
 *
 * In production, the policy signing key is generated by an offline root CA
 * and the private key never leaves the HSM. This script is for development
 * and testing — it generates a self-contained key pair.
 *
 * Usage:
 *   node scripts/generate-policy-root-of-trust.js [--force]
 *
 * Options:
 *   --force    Overwrite an existing key + header file
 *
 * Output files:
 *   .pbl_policy_signing_key              — base64 PKCS8 private key (gitignored)
 *   firmware/PblPkg/PblApp/PolicyRootOfTrust.generated.h — SPKI + kid constants
 *
 * The generated header defines:
 *   #define PBL_POLICY_SIGNING_KEY_SPKI_SIZE  <n>
 *   static CONST UINT8 gPblPolicySigningKeySpki[<n>] = { 0x30, 0x59, ... };
 *   static CONST UINT8 gPblPolicySigningKeyKid[32] = { 0x..., ... };
 *
 * Copyright (c) 2026 Remote Lockdown System. All rights reserved.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const KEY_FILE = path.join(REPO_ROOT, '.pbl_policy_signing_key');
const HEADER_FILE = path.join(REPO_ROOT, 'firmware/PblPkg/PblApp/PolicyRootOfTrust.generated.h');

const FORCE = process.argv.includes('--force');

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function toHexBytes(buf) {
  return Array.from(buf).map(b => '0x' + b.toString(16).padStart(2, '0'));
}

function formatCArray(bytes, perLine) {
  const arr = Array.from(bytes);
  const lines = [];
  for (let i = 0; i < arr.length; i += perLine) {
    const chunk = arr.slice(i, i + perLine);
    lines.push('  ' + chunk.map(b => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  // Check if key already exists
  if (fs.existsSync(KEY_FILE) && !FORCE) {
    console.error('[INFO] Policy signing key already exists at', KEY_FILE);
    console.error('       Use --force to regenerate (WARNING: invalidates all existing policy blobs)');
    process.exit(1);
  }

  // Generate ES256 key pair
  const keyPair = await crypto.subtle.generateKey(
    { name: 'ECDSA', namedCurve: 'P-256' },
    true,
    ['sign', 'verify'],
  );

  // Export SPKI (public key DER)
  const spkiBuf = await crypto.subtle.exportKey('spki', keyPair.publicKey);
  const spki = Buffer.from(spkiBuf);

  // Compute kid = SHA-256(SPKI)
  const kidBuf = await crypto.subtle.digest('SHA-256', spkiBuf);
  const kid = Buffer.from(kidBuf);

  // Export PKCS8 private key
  const pkcs8Buf = await crypto.subtle.exportKey('pkcs8', keyPair.privateKey);
  const pkcs8 = Buffer.from(pkcs8Buf);

  // Write private key (gitignored)
  fs.writeFileSync(KEY_FILE, pkcs8.toString('base64'), { mode: 0o600 });
  console.log('[OK] Wrote policy signing key to', KEY_FILE, '(mode 600)');

  // Generate C header
  const header = `/** @file
  PolicyRootOfTrust.generated.h — Auto-generated policy signing key root of trust.

  DO NOT EDIT BY HAND. Generated by scripts/generate-policy-root-of-trust.js.

  This file defines the pinned policy signing key SPKI (SubjectPublicKeyInfo
  DER) and its SHA-256 fingerprint (kid). The firmware uses these to verify
  policy blob COSE_Sign1 signatures (C4 §1, D-205).

  The corresponding private key is stored in .pbl_policy_signing_key (base64
  PKCS8, gitignored) for server-side use. In production, the private key
  lives in an offline root CA HSM and never leaves.

  Generated: ${new Date().toISOString()}
  SPKI size: ${spki.length} bytes
  kid: ${kid.toString('hex')}
**/

#ifndef PBL_POLICY_ROOT_OF_TRUST_GENERATED_H_
#define PBL_POLICY_ROOT_OF_TRUST_GENERATED_H_

#define PBL_POLICY_SIGNING_KEY_SPKI_SIZE  ${spki.length}

static CONST UINT8 gPblPolicySigningKeySpki[${spki.length}] = {
${formatCArray(spki, 12)}
};

static CONST UINT8 gPblPolicySigningKeyKid[32] = {
${formatCArray(kid, 12)}
};

#endif // PBL_POLICY_ROOT_OF_TRUST_GENERATED_H_
`;

  fs.writeFileSync(HEADER_FILE, header);
  console.log('[OK] Wrote root-of-trust header to', HEADER_FILE);
  console.log('     SPKI size:', spki.length, 'bytes');
  console.log('     kid:', kid.toString('hex'));

  // Verify .gitignore covers the key file
  const gitignore = fs.readFileSync(path.join(REPO_ROOT, '.gitignore'), 'utf8');
  const keyBasename = path.basename(KEY_FILE);
  if (!gitignore.includes(keyBasename)) {
    console.warn('[WARN] .pbl_policy_signing_key is not in .gitignore — adding it');
    fs.appendFileSync(path.join(REPO_ROOT, '.gitignore'), `\n# D-205: Policy signing key (generated by scripts/generate-policy-root-of-trust.js)\n${keyBasename}\n`);
    console.log('[OK] Added', keyBasename, 'to .gitignore');
  }

  console.log('');
  console.log('Next steps:');
  console.log('  1. Set PBL_POLICY_SIGNING_KEY env var for the serverless worker:');
  console.log('     export PBL_POLICY_SIGNING_KEY=$(cat .pbl_policy_signing_key)');
  console.log('  2. Rebuild the firmware (PolicyRootOfTrust.c includes the generated header)');
  console.log('  3. Policy blobs will now be signed by this key and verified by firmware');
}

main().catch(err => {
  console.error('[ERROR]', err);
  process.exit(1);
});
