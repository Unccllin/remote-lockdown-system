#!/usr/bin/env python3
"""Check the Windows installer packaging a company deployment depends on.

Why this exists (docs/WINDOWS-DEPLOYMENT.md): the channel that avoids a SmartScreen prompt is a managed
deployment, and managed deployment has hard requirements a developer build does not — a per-machine MSI
for device-context installs, silent switches, and artefacts whose checksums match what was published. The
1.0.5 MSI was built `perMachine: false`, which under SYSTEM installs into the SYSTEM profile where no
user can see it; nothing in the build would have told you.

Exit codes are the contract: 0 = everything this host can check passed, 1 = a requirement failed.
A missing inspection tool is reported as SKIPPED, never as a pass — the same rule the other gates in this
repository follow.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PACKAGE_JSON = ROOT / "electron" / "package.json"
REQUIRED_ARTEFACTS = ("remote-lockdown-admin", ".msi", ".exe", "lockdown-installer")


def fail(msg: str) -> None:
    print(f"[FAIL] {msg}")


def ok(msg: str) -> None:
    print(f"[ OK ] {msg}")


def skip(msg: str) -> None:
    print(f"[SKIP] {msg}")


def check_packaging_config(package_json: Path) -> int:
    """Per-machine packaging is what makes device-context deployment possible at all."""
    try:
        build = json.loads(package_json.read_text(encoding="utf-8"))["build"]
    except (OSError, KeyError, json.JSONDecodeError) as exc:
        fail(f"cannot read build config from {package_json}: {exc}")
        return 1

    failures = 0
    msi = build.get("msi", {}) or {}
    if msi.get("perMachine") is True:
        ok("msi.perMachine = true (device-context deployment is possible)")
    else:
        fail(
            "msi.perMachine is not true — an MSI installed as SYSTEM lands in the SYSTEM profile, "
            "invisible to the user. Set build.msi.perMachine: true (docs/WINDOWS-DEPLOYMENT.md §2a)."
        )
        failures += 1

    nsis = build.get("nsis", {}) or {}
    if nsis.get("perMachine") is True:
        ok("nsis.perMachine = true")
    else:
        print(
            "[WARN] nsis.perMachine is not true — the .exe installs per-user. That is fine for a "
            "human double-click; for Intune device context it installs into the SYSTEM profile."
        )

    if msi.get("runAfterFinish") is True:
        print("[WARN] msi.runAfterFinish = true — harmless with /qn, confusing for a managed install.")
    return failures


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def check_release_dir(release_dir: Path, require_signature: bool) -> int:
    failures = 0
    artefacts = [p for p in sorted(release_dir.iterdir()) if p.is_file()] if release_dir.is_dir() else []
    if not artefacts:
        fail(f"no artefacts in {release_dir}")
        return 1

    for needle in REQUIRED_ARTEFACTS:
        matches = [p for p in artefacts if needle in p.name]
        if matches:
            ok(f"present: {matches[0].name} ({matches[0].stat().st_size:,} bytes)")
        elif needle == "lockdown-installer":
            print(
                "[WARN] no lockdown-installer.exe in the release — it is generated by the deployment "
                "and served per device, so its absence here is expected outside an agent release."
            )
        else:
            fail(f"missing artefact matching '{needle}'")
            failures += 1

    sums = next((p for p in artefacts if p.name.startswith("SHA256SUMS")), None)
    if sums:
        for line in sums.read_text(encoding="utf-8").splitlines():
            parts = line.split()
            if len(parts) != 2:
                continue
            expected, name = parts
            target = release_dir / name
            if not target.is_file():
                continue
            actual = sha256(target)
            if actual == expected.lower():
                ok(f"sha256 matches for {name}")
            else:
                fail(f"sha256 MISMATCH for {name}: published {expected}, file is {actual}")
                failures += 1
    else:
        skip("no SHA256SUMS file here — checksums are published per platform on the release")

    signer = shutil.which("osslsigncode")
    if signer is None:
        skip("osslsigncode not installed — signature state NOT verified (a skip is not a pass)")
        if require_signature:
            fail("--require-signature was given but no signing tool is available")
            failures += 1
    else:
        for art in [p for p in artefacts if p.suffix.lower() in {".exe", ".msi"}]:
            result = subprocess.run([signer, "verify", "-in", str(art)], capture_output=True, text=True)
            if result.returncode == 0:
                ok(f"signed: {art.name}")
            else:
                print(f"[WARN] unsigned or unverifiable: {art.name} (expected until signing ships)")
                if require_signature:
                    fail(f"--require-signature given, but {art.name} is not validly signed")
                    failures += 1
    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package-json", type=Path, default=DEFAULT_PACKAGE_JSON)
    parser.add_argument("--release-dir", type=Path, default=None)
    parser.add_argument("--require-signature", action="store_true")
    args = parser.parse_args(argv)

    failures = check_packaging_config(args.package_json)
    if args.release_dir is not None:
        failures += check_release_dir(args.release_dir, args.require_signature)

    if failures:
        print(f"\n{failures} requirement(s) failed")
        return 1
    print("\nall checks this host could run passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
