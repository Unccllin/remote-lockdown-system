# Stamp agent/_buildinfo.py with the identity of the tree being built.
#
# Why this is its own script
# --------------------------
# Two build entry points exist: agent/build.ps1 (the agent and its companions) and
# scripts/build-windows-artifacts.ps1 (what CI runs on a v* tag, and the source of the
# binaries published to KV). Only the first stamped the identity, so every release built
# by CI reported `build=unknown.unknown` -- and a version that cannot distinguish two
# builds is not an identity (S286). The stamping lives here so both callers share one
# implementation instead of one owning a copy that the other silently lacks (S359).
#
# The committed _buildinfo.py keeps its `unknown` placeholders: a source checkout must not
# impersonate a release, and agent/tests/test_version_identity.py pins that.
#
# Usage:
#   pwsh -File scripts/stamp-buildinfo.ps1                       # stamp from the source hash
#   pwsh -File scripts/stamp-buildinfo.ps1 -BuildCommit abc1234  # stamp with a known commit
#
# Output: rewrites agent/_buildinfo.py and prints `Build identity: <date>.<commit>`.

[CmdletBinding()]
param(
    # Override the build id, e.g. the commit that produced the tree. Without it the id is a
    # hash of the agent sources, which is what a build host without git can still compute.
    [string]$BuildCommit = '',
    # For a build that does not happen in a normal checkout (the tests pass a temp tree).
    [string]$AgentDir = ''
)

$ErrorActionPreference = 'Stop'

if (-not $AgentDir) {
    $repoRoot = Split-Path -Parent $PSScriptRoot
    $AgentDir = Join-Path $repoRoot 'agent'
}

if (-not (Test-Path (Join-Path $AgentDir 'agent.py'))) {
    # `throw`, not `exit 1`: this script is invoked with `&` from both build entry points, and an
    # `exit` here would take the caller's whole script down mid-build instead of failing one step.
    # The callers run with $ErrorActionPreference = 'Stop', so the message stops the build.
    throw "agent/agent.py not found under '$AgentDir' - cannot stamp a build identity"
}

# Hash every agent source file except the one being written, in a stable order: the id must
# depend on the code, not on directory enumeration order or on the previous stamp.
$hashInput = New-Object System.Text.StringBuilder
$sources = Get-ChildItem -Path $AgentDir -File -Filter *.py |
    Where-Object { $_.Name -ne '_buildinfo.py' } |
    Sort-Object Name
foreach ($f in $sources) {
    [void]$hashInput.Append($f.Name).Append((Get-FileHash $f.FullName -Algorithm SHA256).Hash)
}

$sha = [System.Security.Cryptography.SHA256]::Create()
try {
    $sourceHashBytes = $sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($hashInput.ToString()))
} finally {
    $sha.Dispose()
}
$sourceHash = -join ($sourceHashBytes | ForEach-Object { $_.ToString('x2') })

$commit = if ($BuildCommit) { $BuildCommit } else { $sourceHash.Substring(0, 12) }
$buildDate = (Get-Date).ToUniversalTime().ToString('yyyyMMdd')

$content = @"
# Generated by scripts/stamp-buildinfo.ps1 - do not edit, do not commit.
# The committed defaults in version control stay 'unknown'; this is a stamped build.
BUILD_COMMIT = "$commit"
BUILD_DATE = "$buildDate"
"@

# ASCII, not utf8: Set-Content -Encoding utf8 writes a BOM under Windows PowerShell 5.1, and
# a Python module does not need one. The content is ASCII by construction.
Set-Content -Path (Join-Path $AgentDir '_buildinfo.py') -Value $content -Encoding ascii

Write-Host "Build identity: $buildDate.$commit" -ForegroundColor Green
