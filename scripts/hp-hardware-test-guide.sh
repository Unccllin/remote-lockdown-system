#!/usr/bin/env bash
#
# HP Hardware Test Guide — Complete procedure for testing enforcement paths
# on real HP hardware (spare HP EliteBook).
#
# This script is a GUIDE, not an automated wizard. It prints step-by-step
# instructions with the exact commands to run. Some steps run on the HP
# machine (PowerShell), some run on the dev machine (WSL2 bash).
#
# Usage:
#   bash scripts/hp-hardware-test-guide.sh
#
# The script will display each phase, pause for you to complete it, then
# move to the next. You can also just read it — every command is shown.
#
# Generated 2026-08-27 for the spare HP EliteBook hardware verification.

set -euo pipefail

if [[ -t 1 ]] && command -v tput >/dev/null 2>&1 && [[ "$(tput colors 2>/dev/null || echo 0)" -ge 8 ]]; then
  BOLD=$(tput bold); DIM=$(tput dim); RESET=$(tput sgr0)
  BLUE=$(tput setaf 4); GREEN=$(tput setaf 2); YELLOW=$(tput setaf 3); RED=$(tput setaf 1)
else
  BOLD=""; DIM=""; RESET=""; BLUE=""; GREEN=""; YELLOW=""; RED=""
fi

TOTAL_PHASES=5

_clear() {
  [[ -t 1 ]] || return 0
  if command -v tput >/dev/null 2>&1; then tput clear; else printf '\033[2J\033[3J\033[H'; fi
}

phase() {
  _clear
  printf '\n%s%s  Phase %s/%s — %s%s\n' "$BOLD" "$BLUE" "$1" "$TOTAL_PHASES" "$2" "$RESET"
  printf '%s  ──────────────────────────────────────────────────%s\n\n' "$DIM" "$RESET"
}

say()  { printf '  %s\n' "$1"; }
cmd()  { printf '  %s$ %s%s\n' "$GREEN" "$1" "$RESET"; }
note() { printf '  %s%s%s\n' "$DIM" "$1" "$RESET"; }
warn() { printf '  %s⚠ %s%s\n' "$YELLOW" "$1" "$RESET"; }
pause() {
  printf '\n  %s%s%s ' "$DIM" "${1:-Press Enter to continue}" "$RESET"
  read -r _ || true
}

# Read the admin token (generated by the dev machine before running this guide)
TOKEN_FILE="$(dirname "$0")/../.admin-token-local"
ADMIN_TOKEN=""
if [[ -f "$TOKEN_FILE" ]]; then
  ADMIN_TOKEN=$(cat "$TOKEN_FILE")
fi

WORKER_URL="https://lockdown-serverless.mainacollins196.workers.dev"

# ════════════════════════════════════════════════════════════════════════════
banner() {
  _clear
  printf '\n%s%s  HP Hardware Test Guide%s\n' "$BOLD" "$BLUE" "$RESET"
  printf '%s  %s phases — harness tests + full agent cycle%s\n\n' "$DIM" "$TOTAL_PHASES" "$RESET"
  printf '  This guide walks you through testing all 5 enforcement paths\n'
  printf '  on real HP hardware, then running a full agent↔Worker lockdown\n'
  printf '  cycle.\n\n'
  printf '  %sPrerequisites:%s\n' "$BOLD" "$RESET"
  printf '    • Spare HP EliteBook on the same LAN\n'
  printf '    • Admin account on the HP machine\n'
  printf '    • Python 3.10+ installed on the HP machine\n'
  printf '    • The agent code copied to the HP machine\n'
  printf '    • This dev machine (WSL2) for enrollment + flag-stolen commands\n\n'
  if [[ -z "$ADMIN_TOKEN" ]]; then
    warn "ADMIN_TOKEN not found — run this from the repo root after generating the token."
    exit 1
  fi
  printf '  %sAdmin token:%s %d chars (saved in .admin-token-local)\n' "$BOLD" "$RESET" "${#ADMIN_TOKEN}"
  printf '  %sWorker URL:%s %s\n\n' "$BOLD" "$RESET" "$WORKER_URL"
  pause "Ready to start?"
}

# ════════════════════════════════════════════════════════════════════════════

banner

# ── Phase 1: Prepare the HP machine ────────────────────────────────────────
phase 1 "Prepare the HP machine"

say "On the HP machine, open PowerShell as Administrator:"
cmd "Right-click Start → Windows Terminal (Admin) → PowerShell tab"
echo
say "Check Python is installed:"
cmd "python --version"
note "Need Python 3.10+. If not installed, download from python.org (check 'Add to PATH')."
echo
say "Install the agent's Python dependencies:"
cmd "pip install cryptography==50.0.0 requests==2.34.2"
echo
say "Get the agent code onto the HP machine. Option A — copy from this dev machine:"
cmd "# On the dev machine (WSL2):"
cmd "scp -r agent/ cllin@<HP-IP>:C:\\Users\\<username>\\lockdown-agent\\"
note "Replace <HP-IP> with the spare HP's LAN IP and <username> with the login user."
echo
say "Option B — if the HP machine already has the code from Aug 21, update it:"
cmd "# On the HP machine, in the agent directory:"
cmd "git pull   # if it's a git clone"
note "Or re-copy the agent/ folder from the dev machine to get the latest code."
echo
say "Verify the harness is present:"
cmd "cd C:\\Users\\<username>\\lockdown-agent"
cmd "dir hw_test_harness.py agent.py hp_uefi_lockdown.py bcd_lockdown.py"
echo
say "Create a test lockdown folder with test files:"
cmd "mkdir C:\\lockdown-test"
cmd "echo \"sensitive document content\" > C:\\lockdown-test\\secret.txt"
cmd "echo \"financial data\" > C:\\lockdown-test\\financials.xlsx"
echo
warn "WARNING: The BCD and HP-UEFI tests will modify real BIOS settings."
warn "Only run them on a machine where you're prepared for this."
warn "The harness rolls back BCD changes on failure, but BIOS password"
warn "changes may persist. Have a recovery plan."
echo
pause "Press Enter when the HP machine is ready"

# ── Phase 2: Run the harness tests ─────────────────────────────────────────
phase 2 "Run the hardware test harness"

say "On the HP machine, in the agent directory (Admin PowerShell):"
echo
say "Step 1: Dry run first — check environment detection without executing anything:"
cmd "cd C:\\Users\\<username>\\lockdown-agent"
cmd "python hw_test_harness.py --dry-run"
echo
note "This should print: Platform=Windows, Is HP=True, HP model=<your model>,"
note "Is admin=True, BitLocker=<enabled/disabled>. All tests show SKIP (dry run)."
echo
say "Step 2: Run the safe tests first (encrypt, lock-screen, guardian):"
cmd "python hw_test_harness.py --only encrypt"
cmd "python hw_test_harness.py --only lock-screen"
note "The lock-screen test WILL LOCK YOUR SCREEN. Be prepared to unlock."
cmd "python hw_test_harness.py --only guardian"
note "The guardian test runs for 12 seconds and re-locks the screen."
echo
say "Step 3: Run the BCD test (modifies real boot config):"
cmd "python hw_test_harness.py --only bcd"
note "This suspends BitLocker (if enabled), modifies BCD, then rolls back."
note "If it fails, the rollback should restore the original BCD settings."
echo
say "Step 4: Run the HP UEFI test (modifies real BIOS settings):"
cmd "python hw_test_harness.py --only hp-uefi"
note "This sets a BIOS Setup password and disables USB/PXE/Legacy boot."
note "If it fails, it rolls back BIOS settings but may NOT clear the password."
echo
say "Step 5: Run all tests together and save the artifact:"
cmd "python hw_test_harness.py --artifact hw_test_artifact_hp.json"
echo
say "Copy the artifact back to the dev machine:"
cmd "# On the dev machine (WSL2):"
cmd "scp cl@<HP-IP>:C:\\Users\\<username>\\lockdown-agent\\hw_test_artifact_hp.json agent/"
echo
pause "Press Enter when the harness tests are complete"

# ── Phase 3: Enroll the HP device ──────────────────────────────────────────
phase 3 "Enroll the HP device via the Worker"

say "On the dev machine (WSL2), enroll the HP device:"
echo
say "Get the HP machine's hostname and MAC address first:"
cmd "# On the HP machine (PowerShell):"
cmd "hostname"
cmd "Get-NetAdapter | Select-Object Name, MacAddress | Format-Table"
echo
say "Enroll the device via the Worker API (run on dev machine):"
cmd "curl -sS -X POST ${WORKER_URL}/api/enroll \\"
cmd "  -H \"Content-Type: application/json\" \\"
cmd "  -H \"Authorization: Bearer ${ADMIN_TOKEN}\" \\"
cmd "  -d '{\"hostname\":\"HP-SPARE-HWTEST\",\"owner_name\":\"Hardware Test\"}'"
echo
note "Save the api_key from the response — you'll need it for the agent config."
note "The api_key is only returned once."
echo
say "Verify the device was enrolled:"
cmd "curl -sS ${WORKER_URL}/api/devices \\"
cmd "  -H \"Authorization: Bearer ${ADMIN_TOKEN}\" | python3 -m json.tool"
echo
pause "Press Enter when the device is enrolled and you have the API key"

# ── Phase 4: Run the full agent lockdown cycle ─────────────────────────────
phase 4 "Run the full agent lockdown cycle"

say "On the HP machine, create the agent config:"
echo
cmd "# In the agent directory, create config.json:"
cmd "@'{"
cmd "  \"server_url\": \"${WORKER_URL}\","
cmd "  \"api_key\": \"<PASTE-API-KEY-HERE>\","
cmd "  \"hostname\": \"HP-SPARE-HWTEST\","
cmd "  \"poll_interval\": 10,"
cmd "  \"lockdown_folder\": \"C:\\\\lockdown-test\","
cmd "  \"lock_sentinel\": \"C:\\\\ProgramData\\\\lockdown-agent\\\\.locked\","
cmd "  \"pending_ack_file\": \"C:\\\\ProgramData\\\\lockdown-agent\\\\.pending_ack\","
cmd "  \"recovery_key_file\": \"C:\\\\ProgramData\\\\lockdown-agent\\\\.recovery_key\","
cmd "  \"boot_lock_enabled\": true,"
cmd "  \"verify_tls\": true,"
cmd "  \"server_supports_ack_dedup\": true"
cmd "}'@ | Set-Content config.json"
echo
note "Replace <PASTE-API-KEY-HERE> with the API key from Phase 3."
note "Set boot_lock_enabled=true to test BCD + HP UEFI lockdown during the cycle."
note "Set boot_lock_enabled=false if you only want to test encryption + lock screen."
echo
warn "WARNING: With boot_lock_enabled=true, the agent will modify real BIOS"
warn "settings during lockdown. Have a recovery plan (BIOS password, BitLocker key)."
echo
say "Create the agent state directory:"
cmd "mkdir C:\\ProgramData\\lockdown-agent -Force"
echo
say "Start the agent (it will check in and wait for commands):"
cmd "python agent.py --config config.json"
echo
note "The agent should print 'Agent starting' and check in successfully."
note "It will show 'status=active, poll=300s, command=null'."
note "Leave it running — don't close this terminal."
echo
say "On the dev machine, flag the device as stolen:"
cmd "curl -sS -X POST ${WORKER_URL}/api/devices/<DEVICE-ID>/flag-stolen \\"
cmd "  -H \"Content-Type: application/json\" \\"
cmd "  -H \"Authorization: Bearer ${ADMIN_TOKEN}\" \\"
cmd "  -d '{\"hostname_confirm\":\"HP-SPARE-HWTEST\"}'"
echo
note "Replace <DEVICE-ID> with the device ID from the enroll response."
note "The response should show status=stolen and a pending lockdown command."
echo
say "Watch the agent terminal — within 10-30 seconds it should:"
say "  1. Receive the lockdown command"
say "  2. Encrypt the files in C:\\lockdown-test"
say "  3. Lock the screen"
say "  4. Start the lock guardian"
say "  5. Apply BCD lockdown (if boot_lock_enabled=true)"
say "  6. Apply HP UEFI lockdown (if boot_lock_enabled=true)"
say "  7. Send ACK to the server"
echo
say "Verify the files are encrypted (on the HP machine, in a NEW terminal):"
cmd "dir C:\\lockdown-test"
note "You should see .enc files instead of the original .txt/.xlsx files."
echo
say "Verify the device status on the dev machine:"
cmd "curl -sS ${WORKER_URL}/api/devices/<DEVICE-ID> \\"
cmd "  -H \"Authorization: Bearer ${ADMIN_TOKEN}\""
note "Status should be 'locked' (not 'stolen' — the KV-RACE-001 fix ensures this)."
echo
pause "Press Enter when the lockdown is verified"

# ── Phase 5: Recover and verify unlock ─────────────────────────────────────
phase 5 "Recover the device and verify unlock"

say "On the dev machine, issue the recover command:"
cmd "curl -sS -X POST ${WORKER_URL}/api/devices/<DEVICE-ID>/recover \\"
cmd "  -H \"Content-Type: application/json\" \\"
cmd "  -H \"Authorization: Bearer ${ADMIN_TOKEN}\" \\"
cmd "  -d '{\"hostname_confirm\":\"HP-SPARE-HWTEST\"}'"
echo
note "The response should show status=recovering and a pending unlock command."
note "It also returns the key_material needed for decryption."
echo
say "Watch the agent terminal — within 30-60 seconds it should:"
say "  1. Receive the unlock command with key_material"
say "  2. Decrypt the files in C:\\lockdown-test"
say "  3. Remove the lock sentinel"
say "  4. Remove the lock screen"
say "  5. Roll back BCD lockdown (if it was applied)"
say "  6. Roll back HP UEFI lockdown (if it was applied)"
say "  7. Send ACK to the server"
echo
say "Verify the files are decrypted back to original:"
cmd "dir C:\\lockdown-test"
cmd "type C:\\lockdown-test\\secret.txt"
note "You should see the original .txt/.xlsx files with original content."
echo
say "Verify the device status is back to active:"
cmd "curl -sS ${WORKER_URL}/api/devices/<DEVICE-ID> \\"
cmd "  -H \"Authorization: Bearer ${ADMIN_TOKEN}\""
note "Status should be 'active'."
echo
say "Stop the agent (Ctrl+C in the agent terminal)."
echo
say "Copy the agent log back to the dev machine for the artifact:"
cmd "# On the dev machine (WSL2):"
cmd "scp cl@<HP-IP>:C:\\Users\\<username>\\lockdown-agent\\agent.log agent/hw_test_agent_log_hp.txt"
echo
say "Or redirect the agent output to a file when starting it:"
cmd "python agent.py --config config.json 2>&1 | Tee-Object agent.log"
echo

# ── Summary ────────────────────────────────────────────────────────────────
_clear
printf '\n%s%s  Test Guide Complete%s\n' "$BOLD" "$GREEN" "$RESET"
printf '\n'
printf '  %sArtifacts to collect:%s\n' "$BOLD" "$RESET"
printf '    1. agent/hw_test_artifact_hp.json — harness test results\n'
printf '    2. agent/hw_test_agent_log_hp.txt — full agent cycle log\n'
printf '\n'
printf '  %sEnforcement paths verified:%s\n' "$BOLD" "$RESET"
printf '    E-ENCRYPT     — file encryption/decryption (Fernet)\n'
printf '    E-LOCK-SCREEN — LockWorkStation/tsdiscon\n'
printf '    E-GUARDIAN    — lock guardian thread\n'
printf '    E-BCD         — BCD lockdown (bcdedit)\n'
printf '    E-HP-UEFI     — HP UEFI/BIOS lockdown (WMI)\n'
printf '    E-ACK         — command ACK to server\n'
printf '    E-RECOVERY    — unlock + key release + decrypt\n'
printf '\n'
printf '  %sNext steps:%s\n' "$BOLD" "$RESET"
printf '    1. Send the artifacts back to the dev machine\n'
printf '    2. Tell Devin the results — I will update the graph spec\n'
printf '       enforcement path statuses from verified-in-unit-test to\n'
printf '       verified-on-hardware\n'
printf '    3. If BCD or HP-UEFI failed, check the boot_lock_detail in\n'
printf '       the artifact for the root cause\n'
printf '\n'
printf '  %sWorker URL:%s %s\n' "$BOLD" "$RESET" "$WORKER_URL"
printf '  %sAdmin token:%s in .admin-token-local (delete after testing)\n' "$BOLD" "$RESET"
printf '\n'
