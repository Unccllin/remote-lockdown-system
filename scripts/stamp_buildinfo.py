"""Stamp agent/_buildinfo.py with the identity of the tree being built.

One implementation, three entry points
--------------------------------------
There are three build paths and each ships binaries to a different place:

    agent/build.ps1                    Windows, interactive and MOLE (S357)
    scripts/build-windows-artifacts.ps1 Windows, what CI runs on a v* tag (S359)
    agent/build.sh                      Linux and macOS, what release.yml runs for the
                                        Electron release's bundled agent binaries

The first stamped, the second did not (fixed in S359), and the third still did not when the
Electron release was being prepared — so the GitHub Release would have published Linux and
macOS agents reporting `build=unknown.unknown`, the exact defect S286 fixed. Three
implementations would drift, so the computation lives here and the other two call it:
`scripts/stamp-buildinfo.ps1` is a thin wrapper for the PowerShell callers, and
`agent/build.sh` invokes this file directly.

The committed agent/_buildinfo.py keeps its `unknown` placeholders: a source checkout must
not impersonate a release (agent/tests/test_version_identity.py pins that).

Identity format: `<UTC yyyyMMdd>.<first 12 hex of the source hash>`, where the source hash is
SHA-256 over the concatenation of `<name><sha256-upper-hex of the file>` for every agent/*.py
except `_buildinfo.py`, ordered by name. That is byte-for-byte the scheme the PowerShell
implementation used, so a tree stamped by either path reports the same id.

Usage:
    python3 scripts/stamp_buildinfo.py                       # stamp the checkout's agent/
    python3 scripts/stamp_buildinfo.py --commit abc1234      # known commit instead of a hash
    python3 scripts/stamp_buildinfo.py --agent-dir /tmp/x/agent
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

TEMPLATE = """# Generated by scripts/stamp_buildinfo.py - do not edit, do not commit.
# The committed defaults in version control stay 'unknown'; this is a stamped build.
BUILD_COMMIT = "{commit}"
BUILD_DATE = "{date}"
"""


def source_hash(agent_dir: Path) -> str:
    """SHA-256 over `<name><sha256 of file>` for every agent source except _buildinfo.py.

    Ordering is by name, never by directory order: the id must depend on the code and not on
    how a filesystem happens to enumerate it.
    """
    digest = hashlib.sha256()
    for path in sorted(agent_dir.glob("*.py"), key=lambda p: p.name):
        if path.name == "_buildinfo.py":
            continue
        digest.update(path.name.encode("utf-8"))
        digest.update(hashlib.sha256(path.read_bytes()).hexdigest().upper().encode("utf-8"))
    return digest.hexdigest()


def stamp(agent_dir: Path, commit: str = "", date: str = "") -> tuple[str, str]:
    """Write agent/_buildinfo.py and return the (date, commit) pair that was written."""
    if not (agent_dir / "agent.py").is_file():
        raise SystemExit(f"agent/agent.py not found under '{agent_dir}' - cannot stamp a build identity")

    resolved_commit = commit or source_hash(agent_dir)[:12]
    resolved_date = date or datetime.now(timezone.utc).strftime("%Y%m%d")

    target = agent_dir / "_buildinfo.py"
    # ASCII with no BOM: a Python module needs neither, and Windows PowerShell 5.1 writes a BOM
    # with -Encoding utf8, which is why the generated content never carries one.
    target.write_text(
        TEMPLATE.format(commit=resolved_commit, date=resolved_date),
        encoding="ascii",
        newline="\n",
    )
    return resolved_date, resolved_commit


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Stamp agent/_buildinfo.py with this tree's build identity")
    parser.add_argument("--agent-dir", default=str(REPO / "agent"), help="agent directory to stamp")
    parser.add_argument("--commit", default="", help="build id to use instead of the source hash")
    parser.add_argument("--date", default="", help="UTC yyyyMMdd to use instead of today")
    args = parser.parse_args(argv)

    date, commit = stamp(Path(args.agent_dir), args.commit, args.date)
    print(f"Build identity: {date}.{commit}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
